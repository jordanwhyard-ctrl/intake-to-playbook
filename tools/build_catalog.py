"""Build the ISV catalog used by the inventory sample.

Inputs (all in tools/ and the sample's reference/ folder):
  tools/isv_list.tsv              the ISVs to cover: product, vendor, category, search term
  tools/marketplace_evidence.tsv  AWS / Microsoft marketplace status per product, with the
                                  listing URL found as evidence
  reference/curated.yaml          hand-written extras: aliases, curated alternatives, suite coverage
  reference/partner_program.yaml  the consultant's resale / services / marketplace agreements

Output:
  reference/isv_catalog.yaml      the catalog intake matches inventory lines against
  docs/isv_marketplace_catalog.md human-readable table with evidence links

Run:  python tools/build_catalog.py
"""
from __future__ import annotations

import csv
from collections import defaultdict
from datetime import date
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SAMPLE = ROOT / "samples" / "01-isv-inventory"
REF = SAMPLE / "reference"

STATUS_TEXT = {
    "listed": "Listed",
    "app": "App/add-in only",
    "not_found": "Not found",
    "first_party": "First-party (sold by Microsoft)",
    "unverified": "Not yet verified",
    "n_a": "n/a (Microsoft product)",
}


def main() -> None:
    isvs = list(csv.DictReader((ROOT / "tools" / "isv_list.tsv").open(encoding="utf-8"), delimiter="\t"))
    evidence = {r["product"]: r for r in csv.DictReader((ROOT / "tools" / "marketplace_evidence.tsv").open(encoding="utf-8"), delimiter="\t")}
    curated = yaml.safe_load((REF / "curated.yaml").read_text(encoding="utf-8")) or {}
    partners = yaml.safe_load((REF / "partner_program.yaml").read_text(encoding="utf-8"))["vendors"]

    rename = curated.get("canonical_names", {})
    extras = curated.get("products", {})
    rows = []
    for r in isvs:
        name = rename.get(r["product"], r["product"])
        rows.append({"product": name, "list_name": r["product"], "vendor": r["vendor"], "category": r["category"],
                     "search": r["search"]})
    names = {r["product"] for r in rows}
    by_cat: dict[str, list[dict]] = defaultdict(list)
    for r in rows:
        by_cat[r["category"]].append(r)

    def mp(r: dict, side: str) -> tuple[str, str]:
        ev = evidence.get(r["list_name"])
        if not ev:
            return "unverified", ""
        status = ev.get("aws" if side == "aws" else "microsoft") or "unverified"
        url = ev.get("aws_url" if side == "aws" else "microsoft_url") or ""
        if status == "?":
            status = "unverified"
        return status, url

    entries = []
    for r in rows:
        x = extras.get(r["product"], {})
        aliases = list(dict.fromkeys([a.lower() for a in x.get("aliases", [])] +
                                     ([r["search"].lower()] if r["search"].lower() != r["product"].lower() else []) +
                                     ([r["list_name"].lower()] if r["list_name"] != r["product"] else [])))
        alts = x.get("alternatives")
        if not alts:
            peers = [p for p in by_cat[r["category"]] if p["product"] != r["product"]]
            peers.sort(key=lambda p: (mp(p, "aws")[0] != "listed" and mp(p, "azure")[0] != "listed", p["product"]))
            alts = [p["product"] for p in peers[:4]]
        alts = [a for a in alts if a != r["product"]]
        vendor_of = {p["product"]: p["vendor"] for p in rows}
        partner_alts = [a for a in alts if vendor_of.get(a) in partners]
        aws_s, aws_u = mp(r, "aws")
        az_s, az_u = mp(r, "azure")
        e = {"product": r["product"]}
        if aliases:
            e["aliases"] = aliases
        e.update(vendor=r["vendor"], category=r["category"], alternatives=alts, partner_alternatives=partner_alts)
        p = partners.get(r["vendor"])
        if p and p.get("resale_margin"):
            e["resale_margin"] = p["resale_margin"]
        if p and p.get("services"):
            e["partner_services"] = True
        if p and p.get("marketplace"):
            e["partner_marketplace_programs"] = p["marketplace"]
        e["aws_marketplace"] = aws_s
        if aws_u:
            e["aws_listing"] = aws_u
        e["azure_marketplace"] = az_s
        if az_u:
            e["azure_listing"] = az_u
        e["marketplaces"] = [m for m, s in (("AWS", aws_s), ("Azure", az_s)) if s == "listed"]
        for k in ("covered_by", "covered_by_suites"):
            if k in x:
                e[k] = x[k]
        entries.append(e)

    missing_alts = sorted({a for e in entries for a in e["alternatives"] if a not in names})
    header = (
        "# GENERATED by tools/build_catalog.py — edit tools/*.tsv or reference/curated.yaml, then rebuild.\n"
        f"# {len(entries)} products. Marketplace status checked {date.today():%B %Y} by searching each marketplace;\n"
        "# the listing URL is the evidence. 'not_found' means no ISV-published listing turned up, not proof that\n"
        "# none exists. 'app' means only a Teams/Office add-in or Entra gallery app, not a purchasable offer.\n"
        "# Alternatives, margins and suite coverage are illustrative assumptions.\n"
    )
    (REF / "isv_catalog.yaml").write_text(header + yaml.safe_dump({"entries": entries}, sort_keys=False, allow_unicode=True, width=120),
                                          encoding="utf-8")

    # human-readable table
    counts = defaultdict(int)
    for e in entries:
        counts[("aws", e["aws_marketplace"])] += 1
        counts[("azure", e["azure_marketplace"])] += 1
    out = ["# ISV marketplace catalog", "",
           f"{len(entries)} ISV products across {len(by_cat)} categories, with their AWS Marketplace and Microsoft "
           f"(Azure) Marketplace status and the listing found as evidence. Checked {date.today():%B %Y}.", "",
           "| Status | AWS | Microsoft |", "|---|---|---|"]
    for s in ("listed", "app", "first_party", "n_a", "not_found", "unverified"):
        out.append(f"| {STATUS_TEXT[s]} | {counts[('aws', s)]} | {counts[('azure', s)]} |")
    out += ["", "*Listed* = an ISV-published offer was found. *App/add-in only* = only a Teams/Office add-in or Entra "
            "gallery app, which isn't a purchasable software offer. *Not found* = no ISV-published listing turned up "
            "in a domain-restricted search; that is not proof none exists. *Not yet verified* = still to check.", ""]
    for cat in sorted(by_cat):
        out += [f"## {cat}", "", "| Product | Vendor | AWS Marketplace | Microsoft Marketplace | Alternatives |", "|---|---|---|---|---|"]
        for e in sorted((e for e in entries if e["category"] == cat), key=lambda e: e["product"]):
            def cell(s, u):
                t = STATUS_TEXT[s]
                return f"[{t}]({u})" if u else t
            out.append(f"| {e['product']} | {e['vendor']} | {cell(e['aws_marketplace'], e.get('aws_listing'))} | "
                       f"{cell(e['azure_marketplace'], e.get('azure_listing'))} | {', '.join(e['alternatives'])} |")
        out.append("")
    out.append("Product names and trademarks belong to their owners. Listing status changes often; re-check before quoting.")
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "isv_marketplace_catalog.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{len(entries)} products written; alternatives not in catalog: {missing_alts or 'none'}")
    print({f"{k[0]}:{k[1]}": v for k, v in sorted(counts.items())})


if __name__ == "__main__":
    main()
